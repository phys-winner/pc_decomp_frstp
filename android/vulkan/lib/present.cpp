uint64_t now_ns() { timespec t; clock_gettime(CLOCK_MONOTONIC, &t); return uint64_t(t.tv_sec) * 1000000000ull + uint64_t(t.tv_nsec); }

/* The Graphics row "Upscaling" (port_settings.c): 0 bilinear by the compositor, 1 FSR 1, 2 FSR 3. */
int upscaler_mode() {
    static int (*const get)() = reinterpret_cast<int (*)()>(dlsym(RTLD_DEFAULT, "frostpunk_dxvk_upscaler"));
    int mode = get ? get() : 0;
    if (mode == 2) {
        static bool logged = false;
        if (!logged) { logged = true; log("RDVK_UPSCALER FSR 3 is not available on the native renderer; using FSR 1"); }
        return 1;
    }
    return mode == 1 ? 1 : 0;
}

struct FsrPass {
    VkDescriptorSetLayout set_layout = VK_NULL_HANDLE;
    VkPipelineLayout layout = VK_NULL_HANDLE;
    VkSampler sampler = VK_NULL_HANDLE;
    VkShaderModule vs = VK_NULL_HANDLE, fs = VK_NULL_HANDLE;
    VkPipeline pipeline = VK_NULL_HANDLE;
    VkFormat format = VK_FORMAT_UNDEFINED;
    uint32_t width = 0, height = 0;
} fsr;

VkShaderModule shader_module(const uint32_t* code, size_t bytes) {
    VkShaderModuleCreateInfo info{VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO};
    info.codeSize = bytes;
    info.pCode = code;
    VkShaderModule module = VK_NULL_HANDLE;
    vk_check(vk.vkCreateShaderModule(gpu.device, &info, nullptr, &module), "vkCreateShaderModule(present)");
    return module;
}

/* The EASU pipeline for this output format and size (specialization constants 3 and 4). */
bool fsr_ready(VkFormat format, uint32_t width, uint32_t height) {
    if (!gpu.caps.push_descriptor) return false;
    if (!fsr.layout) {
        VkDescriptorSetLayoutBinding binding{0, VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, 1, VK_SHADER_STAGE_FRAGMENT_BIT, nullptr};
        VkDescriptorSetLayoutCreateInfo set{VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO};
        set.flags = VK_DESCRIPTOR_SET_LAYOUT_CREATE_PUSH_DESCRIPTOR_BIT_KHR;
        set.bindingCount = 1;
        set.pBindings = &binding;
        vk_check(vk.vkCreateDescriptorSetLayout(gpu.device, &set, nullptr, &fsr.set_layout), "vkCreateDescriptorSetLayout(fsr)");
        VkPushConstantRange push{VK_SHADER_STAGE_FRAGMENT_BIT, 0, 16};
        VkPipelineLayoutCreateInfo info{VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO};
        info.setLayoutCount = 1; info.pSetLayouts = &fsr.set_layout;
        info.pushConstantRangeCount = 1; info.pPushConstantRanges = &push;
        vk_check(vk.vkCreatePipelineLayout(gpu.device, &info, nullptr, &fsr.layout), "vkCreatePipelineLayout(fsr)");
        VkSamplerCreateInfo sampler{VK_STRUCTURE_TYPE_SAMPLER_CREATE_INFO};
        sampler.magFilter = sampler.minFilter = VK_FILTER_LINEAR;
        sampler.addressModeU = sampler.addressModeV = sampler.addressModeW = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
        sampler.maxLod = 0.25f;
        vk_check(vk.vkCreateSampler(gpu.device, &sampler, nullptr, &fsr.sampler), "vkCreateSampler(fsr)");
        fsr.vs = shader_module(kFullscreenVert, sizeof(kFullscreenVert));
        fsr.fs = shader_module(kFsr1EasuFrag, sizeof(kFsr1EasuFrag));
    }
    if (fsr.pipeline && fsr.format == format && fsr.width == width && fsr.height == height) return true;
    if (fsr.pipeline) { VkPipeline old = fsr.pipeline; gpu.defer([old] { vk.vkDestroyPipeline(gpu.device, old, nullptr); }); fsr.pipeline = VK_NULL_HANDLE; }
    uint32_t constants[2] = {width, height};
    VkSpecializationMapEntry entries[2] = {{3, 0, 4}, {4, 4, 4}};
    VkSpecializationInfo spec{2, entries, sizeof(constants), constants};
    VkPipelineShaderStageCreateInfo stages[2] = {{VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO}, {VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO}};
    stages[0].stage = VK_SHADER_STAGE_VERTEX_BIT; stages[0].module = fsr.vs; stages[0].pName = "main";
    stages[1].stage = VK_SHADER_STAGE_FRAGMENT_BIT; stages[1].module = fsr.fs; stages[1].pName = "main"; stages[1].pSpecializationInfo = &spec;
    VkPipelineVertexInputStateCreateInfo input{VK_STRUCTURE_TYPE_PIPELINE_VERTEX_INPUT_STATE_CREATE_INFO};
    VkPipelineInputAssemblyStateCreateInfo assembly{VK_STRUCTURE_TYPE_PIPELINE_INPUT_ASSEMBLY_STATE_CREATE_INFO};
    assembly.topology = VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST;
    VkPipelineViewportStateCreateInfo viewport{VK_STRUCTURE_TYPE_PIPELINE_VIEWPORT_STATE_CREATE_INFO};
    viewport.viewportCount = 1; viewport.scissorCount = 1;
    VkPipelineRasterizationStateCreateInfo raster{VK_STRUCTURE_TYPE_PIPELINE_RASTERIZATION_STATE_CREATE_INFO};
    raster.polygonMode = VK_POLYGON_MODE_FILL; raster.cullMode = VK_CULL_MODE_NONE; raster.lineWidth = 1.0f;
    VkPipelineMultisampleStateCreateInfo multisample{VK_STRUCTURE_TYPE_PIPELINE_MULTISAMPLE_STATE_CREATE_INFO};
    multisample.rasterizationSamples = VK_SAMPLE_COUNT_1_BIT;
    VkPipelineColorBlendAttachmentState attachment{};
    attachment.colorWriteMask = VK_COLOR_COMPONENT_R_BIT | VK_COLOR_COMPONENT_G_BIT | VK_COLOR_COMPONENT_B_BIT | VK_COLOR_COMPONENT_A_BIT;
    VkPipelineColorBlendStateCreateInfo blend{VK_STRUCTURE_TYPE_PIPELINE_COLOR_BLEND_STATE_CREATE_INFO};
    blend.attachmentCount = 1; blend.pAttachments = &attachment;
    VkDynamicState dynamic_states[2] = {VK_DYNAMIC_STATE_VIEWPORT, VK_DYNAMIC_STATE_SCISSOR};
    VkPipelineDynamicStateCreateInfo dynamic{VK_STRUCTURE_TYPE_PIPELINE_DYNAMIC_STATE_CREATE_INFO};
    dynamic.dynamicStateCount = 2; dynamic.pDynamicStates = dynamic_states;
    VkPipelineRenderingCreateInfo rendering{VK_STRUCTURE_TYPE_PIPELINE_RENDERING_CREATE_INFO};
    rendering.colorAttachmentCount = 1; rendering.pColorAttachmentFormats = &format;
    VkGraphicsPipelineCreateInfo info{VK_STRUCTURE_TYPE_GRAPHICS_PIPELINE_CREATE_INFO, &rendering};
    info.stageCount = 2; info.pStages = stages;
    info.pVertexInputState = &input; info.pInputAssemblyState = &assembly; info.pViewportState = &viewport;
    info.pRasterizationState = &raster; info.pMultisampleState = &multisample; info.pColorBlendState = &blend;
    info.pDynamicState = &dynamic; info.layout = fsr.layout;
    if (vk.vkCreateGraphicsPipelines(gpu.device, VK_NULL_HANDLE, 1, &info, nullptr, &fsr.pipeline) != VK_SUCCESS) {
        fsr.pipeline = VK_NULL_HANDLE;
        return false;
    }
    fsr.format = format; fsr.width = width; fsr.height = height;
    log("RDVK_FSR1 EASU pipeline %ux%u format=%d", width, height, int(format));
    return true;
}

void destroy_swapchain(SwapChainObject* s) {
    if (s->swapchain || s->surface) gpu.wait_idle();
    for (VkSemaphore& x : s->acquire) if (x) { vk.vkDestroySemaphore(gpu.device, x, nullptr); x = VK_NULL_HANDLE; }
    for (VkSemaphore& x : s->rendered) if (x) vk.vkDestroySemaphore(gpu.device, x, nullptr);
    s->rendered.clear();
    for (VkImageView v : s->views) vk.vkDestroyImageView(gpu.device, v, nullptr);
    s->views.clear();
    if (s->back_view) vk.vkDestroyImageView(gpu.device, s->back_view, nullptr);
    s->back_view = VK_NULL_HANDLE;
    s->back_view_of = nullptr;
    s->images.clear();
    if (s->swapchain) vk.vkDestroySwapchainKHR(gpu.device, s->swapchain, nullptr);
    s->swapchain = VK_NULL_HANDLE;
    if (s->surface) vk.vkDestroySurfaceKHR(gpu.instance, s->surface, nullptr);
    s->surface = VK_NULL_HANDLE;
    if (s->window) host->window_release(s->window);
    s->window = nullptr;
}

bool create_swapchain(SwapChainObject* s) {
    if (!s->window) {
        uint64_t generation = 0;
        s->window = host->window_acquire(s->hwnd, &generation);
        s->generation = generation;
        if (!s->window) return false;
    }
    if (!s->surface) {
        VkAndroidSurfaceCreateInfoKHR info{VK_STRUCTURE_TYPE_ANDROID_SURFACE_CREATE_INFO_KHR};
        info.window = static_cast<ANativeWindow*>(s->window);
        VkResult r = vk.vkCreateAndroidSurfaceKHR(gpu.instance, &info, nullptr, &s->surface);
        if (r != VK_SUCCESS) { log("RDVK_SURFACE_FAILED %s", vk_result(r)); return false; }
        VkBool32 supported = VK_FALSE;
        vk.vkGetPhysicalDeviceSurfaceSupportKHR(gpu.physical, gpu.family, s->surface, &supported);
        if (!supported) { log("RDVK_SURFACE_UNSUPPORTED"); return false; }
    }
    VkSurfaceCapabilitiesKHR caps;
    if (vk.vkGetPhysicalDeviceSurfaceCapabilitiesKHR(gpu.physical, s->surface, &caps) != VK_SUCCESS) return false;
    uint32_t count = 0;
    vk.vkGetPhysicalDeviceSurfaceFormatsKHR(gpu.physical, s->surface, &count, nullptr);
    std::vector<VkSurfaceFormatKHR> formats(count);
    vk.vkGetPhysicalDeviceSurfaceFormatsKHR(gpu.physical, s->surface, &count, formats.data());
    VkSurfaceFormatKHR chosen = formats.empty() ? VkSurfaceFormatKHR{VK_FORMAT_R8G8B8A8_UNORM, VK_COLOR_SPACE_SRGB_NONLINEAR_KHR} : formats[0];
    for (const VkSurfaceFormatKHR& f : formats)
        if (f.format == VK_FORMAT_R8G8B8A8_UNORM && f.colorSpace == VK_COLOR_SPACE_SRGB_NONLINEAR_KHR) chosen = f;
    vk.vkGetPhysicalDeviceSurfacePresentModesKHR(gpu.physical, s->surface, &count, nullptr);
    std::vector<VkPresentModeKHR> modes(count);
    vk.vkGetPhysicalDeviceSurfacePresentModesKHR(gpu.physical, s->surface, &count, modes.data());
    VkPresentModeKHR mode = VK_PRESENT_MODE_FIFO_KHR;
    for (VkPresentModeKHR m : modes) if (m == VK_PRESENT_MODE_MAILBOX_KHR) mode = m;
    VkSwapchainCreateInfoKHR info{VK_STRUCTURE_TYPE_SWAPCHAIN_CREATE_INFO_KHR};
    info.surface = s->surface;
    info.minImageCount = std::max(caps.minImageCount, 3u);
    if (caps.maxImageCount) info.minImageCount = std::min(info.minImageCount, caps.maxImageCount);
    info.imageFormat = chosen.format;
    info.imageColorSpace = chosen.colorSpace;
    s->upscaler = upscaler_mode();
    VkExtent2D extent{s->width, s->height};
    if (s->upscaler && caps.currentExtent.width != 0xFFFFFFFFu && caps.currentExtent.width > s->width && caps.currentExtent.height > s->height)
        extent = caps.currentExtent;
    s->out_width = extent.width; s->out_height = extent.height;
    info.imageExtent = extent;
    info.imageArrayLayers = 1;
    info.imageUsage = VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT;
    info.imageSharingMode = VK_SHARING_MODE_EXCLUSIVE;
    info.preTransform = (caps.supportedTransforms & VK_SURFACE_TRANSFORM_IDENTITY_BIT_KHR) ? VK_SURFACE_TRANSFORM_IDENTITY_BIT_KHR : caps.currentTransform;
    info.compositeAlpha = (caps.supportedCompositeAlpha & VK_COMPOSITE_ALPHA_OPAQUE_BIT_KHR) ? VK_COMPOSITE_ALPHA_OPAQUE_BIT_KHR : VK_COMPOSITE_ALPHA_INHERIT_BIT_KHR;
    info.presentMode = mode;
    info.clipped = VK_TRUE;
    info.oldSwapchain = s->swapchain;
    VkSwapchainKHR swapchain = VK_NULL_HANDLE;
    VkResult r = vk.vkCreateSwapchainKHR(gpu.device, &info, nullptr, &swapchain);
    if (s->swapchain) { vk.vkDestroySwapchainKHR(gpu.device, s->swapchain, nullptr); s->swapchain = VK_NULL_HANDLE; }
    if (r != VK_SUCCESS) { log("RDVK_SWAPCHAIN_FAILED %s %ux%u", vk_result(r), s->out_width, s->out_height); return false; }
    s->swapchain = swapchain;
    s->recreate = false;
    s->format = chosen.format;
    vk.vkGetSwapchainImagesKHR(gpu.device, swapchain, &count, nullptr);
    s->images.resize(count);
    vk.vkGetSwapchainImagesKHR(gpu.device, swapchain, &count, s->images.data());
    for (VkImageView v : s->views) vk.vkDestroyImageView(gpu.device, v, nullptr);
    s->views.assign(count, VK_NULL_HANDLE);
    for (uint32_t i = 0; i < count; ++i) {
        VkImageViewCreateInfo view{VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO};
        view.image = s->images[i]; view.viewType = VK_IMAGE_VIEW_TYPE_2D; view.format = chosen.format;
        view.subresourceRange = VkImageSubresourceRange{VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
        vk_check(vk.vkCreateImageView(gpu.device, &view, nullptr, &s->views[i]), "vkCreateImageView(swapchain)");
    }
    for (VkSemaphore& x : s->rendered) vk.vkDestroySemaphore(gpu.device, x, nullptr);
    s->rendered.assign(count, VK_NULL_HANDLE);
    VkSemaphoreCreateInfo si{VK_STRUCTURE_TYPE_SEMAPHORE_CREATE_INFO};
    for (VkSemaphore& x : s->rendered) vk_check(vk.vkCreateSemaphore(gpu.device, &si, nullptr, &x), "vkCreateSemaphore");
    for (VkSemaphore& x : s->acquire) if (!x) vk_check(vk.vkCreateSemaphore(gpu.device, &si, nullptr, &x), "vkCreateSemaphore");
    log("RDVK_SWAPCHAIN %ux%u images=%u format=%d mode=%d transform=0x%x generation=%llu back=%ux%u upscaler=%d", s->out_width, s->out_height,
        count, int(s->format), int(mode), unsigned(info.preTransform), (unsigned long long)s->generation, s->width, s->height, s->upscaler);
    /* Same marker as DXVK's presenter: the measurement tools wait for it at the title screen. */
    log("info:  Presenter: Actual swap chain properties:");
    if (host->render_log) {
        char line[160];
        snprintf(line, sizeof(line), "native vulkan swapchain %ux%u images=%u mode=%d", s->out_width, s->out_height, count, int(mode));
        host->render_log(line);
    }
    return true;
}

/* The activity's window was replaced (background/resume): a new surface is needed. */
bool window_changed(SwapChainObject* s) {
    uint64_t generation = 0;
    void* current = host->window_acquire(s->hwnd, &generation);
    bool changed = !current || current != s->window || generation != s->generation;
    if (current) host->window_release(current);
    return changed;
}
