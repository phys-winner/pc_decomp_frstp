/* DXGI swap chain of the native device: the engine renders into a private back buffer texture,
 * Present copies it into an Android Vulkan swap chain image of the same size (the Android
 * compositor scales a smaller buffer to the window, as with DXVK).  With "Upscaling" = FSR the
 * swap chain has the window size and an AMD FSR 1 EASU pass draws the back buffer into it (FSR 3
 * of the DXVK path is not available here and uses FSR 1). */
