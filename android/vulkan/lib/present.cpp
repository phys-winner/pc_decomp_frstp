SwapChainObject* swapchain_create(uint64_t hwnd, const d3d::SWAP_CHAIN_DESC1& desc) {
    auto* s = new SwapChainObject();
    s->hwnd = hwnd;
    s->desc = desc;
    s->width = desc.Width ? desc.Width : 1280;
    s->height = desc.Height ? desc.Height : 720;
    d3d::TEXTURE2D_DESC t{};
    t.Width = s->width; t.Height = s->height; t.MipLevels = 1; t.ArraySize = 1; t.Format = desc.Format ? desc.Format : 28;
    t.SampleDesc.Count = 1; t.Usage = d3d::USAGE_DEFAULT; t.BindFlags = d3d::BIND_RENDER_TARGET | d3d::BIND_SHADER_RESOURCE;
    if (create_texture(2, &t, nullptr, &s->back) != d3d::HR_S_OK) stop("back buffer %ux%u", s->width, s->height);
    if (!create_swapchain(s)) log("RDVK_SWAPCHAIN_DEFERRED no window yet");
    return s;
}

uint32_t swapchain_resize(SwapChainObject* s, uint32_t width, uint32_t height, uint32_t format) {
    g_ctx.flush();
    gpu.wait_idle();
    if (width) s->width = width;
    if (height) s->height = height;
    if (format) s->desc.Format = format;
    if (s->back && s->back->refs.load() > 1) log("RDVK_RESIZE back buffer still referenced (%d)", s->back->refs.load());
    release(s->back);
    s->back = nullptr;
    d3d::TEXTURE2D_DESC t{};
    t.Width = s->width; t.Height = s->height; t.MipLevels = 1; t.ArraySize = 1; t.Format = s->desc.Format ? s->desc.Format : 28;
    t.SampleDesc.Count = 1; t.Usage = d3d::USAGE_DEFAULT; t.BindFlags = d3d::BIND_RENDER_TARGET | d3d::BIND_SHADER_RESOURCE;
    if (create_texture(2, &t, nullptr, &s->back) != d3d::HR_S_OK) stop("back buffer %ux%u", s->width, s->height);
    create_swapchain(s);
    return d3d::HR_S_OK;
}

void swapchain_destroy(Object* o) {
    auto* s = static_cast<SwapChainObject*>(o);
    destroy_swapchain(s);
    release(s->back);
    delete s;
}

void Context::present(SwapChainObject* s, uint32_t interval) {
    (void)interval;
    geometry::present();
    com_census_frame();
    if (host->frame_pace) host->frame_pace();
    end_pass(PE_PRESENT);
    VkCommandBuffer cmd = gpu.cmd();
    cmd_ = cmd;
    sweep_attachments();
    if (s && gpu.caps.driver_id == VK_DRIVER_ID_MESA_PANVK && frostpunk_android_foreground &&
        frostpunk_android_wait_foreground && !frostpunk_android_foreground()) {
        flush_barriers();
        gpu.submit();
        if (s->surface || s->swapchain) destroy_swapchain(s);
        else gpu.wait_idle();
        cmd = cmd_ = gpu.cmd();
        reset_command_state();
        log("RDVK_SUSPEND generation=%llu", (unsigned long long)s->generation);
        if (!frostpunk_android_wait_foreground()) return;
        log("RDVK_RESUME");
    }
    bool presented = false;
    /* Acquisition and a queued presentation can both access the same swapchain on the host. */
    if (s) gpu.wait_submissions();
    if (s && (!s->swapchain || s->recreate || window_changed(s) || upscaler_mode() != s->upscaler)) {
        if (s->swapchain || s->surface) {
            flush_barriers();
            gpu.submit();
            destroy_swapchain(s);
            cmd = cmd_ = gpu.cmd();
        }
        create_swapchain(s);
    }
    if (s && s->swapchain && s->back) {
        VkSemaphore acquire = s->acquire[s->acquire_index];
        uint32_t index = 0;
        uint64_t acquire_start = now_ns();
        VkResult result = vk.vkAcquireNextImageKHR(gpu.device, s->swapchain, 2000000000ull, acquire, VK_NULL_HANDLE, &index);
        gpu.sync.acquire_ns += now_ns() - acquire_start;
        /* A lost surface is rebuilt with a new VkSurfaceKHR on the next frame (T04 a/b). */
        if (result == VK_ERROR_SURFACE_LOST_KHR || result == VK_ERROR_OUT_OF_DATE_KHR) {
            if (first_time("acquire_lost")) log("RDVK_SURFACE_REBUILD acquire returned %s", vk_result(result));
            s->recreate = true;
        }
        if (result == VK_ERROR_DEVICE_LOST) stop("vkAcquireNextImageKHR: %s", vk_result(result));
        if (result == VK_SUCCESS || result == VK_SUBOPTIMAL_KHR) {
            Texture* back = s->back;
            bool upscale = s->upscaler && (s->out_width > back->width || s->out_height > back->height) &&
                           index < s->views.size() && fsr_ready(s->format, s->out_width, s->out_height);
            if (upscale && s->back_view_of != back) {
                if (s->back_view) { VkImageView old = s->back_view; gpu.defer([old] { vk.vkDestroyImageView(gpu.device, old, nullptr); }); }
                VkImageViewCreateInfo view{VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO};
                view.image = back->image; view.viewType = VK_IMAGE_VIEW_TYPE_2D; view.format = back->vk_format;
                view.subresourceRange = VkImageSubresourceRange{VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
                vk_check(vk.vkCreateImageView(gpu.device, &view, nullptr, &s->back_view), "vkCreateImageView(back)");
                s->back_view_of = back;
            }
            if (upscale) {
                /* FSR 1 EASU from the back buffer into the window-size swap chain image. */
                transition(back, VkImageSubresourceRange{VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1}, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL);
                VkImageMemoryBarrier b{VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER};
                b.oldLayout = VK_IMAGE_LAYOUT_UNDEFINED; b.newLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
                b.dstAccessMask = VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT;
                b.srcQueueFamilyIndex = b.dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
                b.image = s->images[index];
                b.subresourceRange = VkImageSubresourceRange{VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
                barrier(b, VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT, VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT);
                flush_barriers();
                VkRenderingAttachmentInfo target{VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO};
                target.imageView = s->views[index];
                target.imageLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
                target.loadOp = VK_ATTACHMENT_LOAD_OP_DONT_CARE;
                target.storeOp = VK_ATTACHMENT_STORE_OP_STORE;
                VkRenderingInfo rendering{VK_STRUCTURE_TYPE_RENDERING_INFO};
                rendering.renderArea = VkRect2D{{0, 0}, {s->out_width, s->out_height}};
                rendering.layerCount = 1;
                rendering.colorAttachmentCount = 1;
                rendering.pColorAttachments = &target;
                vk.vkCmdBeginRendering(cmd, &rendering);
                vk.vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, fsr.pipeline);
                VkViewport viewport{0.0f, 0.0f, float(s->out_width), float(s->out_height), 0.0f, 1.0f};
                VkRect2D scissor{{0, 0}, {s->out_width, s->out_height}};
                vk.vkCmdSetViewport(cmd, 0, 1, &viewport);
                vk.vkCmdSetScissor(cmd, 0, 1, &scissor);
                VkDescriptorImageInfo image{fsr.sampler, s->back_view, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL};
                VkWriteDescriptorSet write{VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET};
                write.dstBinding = 0; write.descriptorCount = 1; write.descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
                write.pImageInfo = &image;
                vk.vkCmdPushDescriptorSetKHR(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, fsr.layout, 0, 1, &write);
                uint32_t source[4] = {0, 0, back->width, back->height};
                vk.vkCmdPushConstants(cmd, fsr.layout, VK_SHADER_STAGE_FRAGMENT_BIT, 0, sizeof(source), source);
                vk.vkCmdDraw(cmd, 3, 1, 0, 0);
                vk.vkCmdEndRendering(cmd);
                b.oldLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL; b.newLayout = VK_IMAGE_LAYOUT_PRESENT_SRC_KHR;
                b.srcAccessMask = VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT; b.dstAccessMask = 0;
                vk.vkCmdPipelineBarrier(cmd, VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT, VK_PIPELINE_STAGE_BOTTOM_OF_PIPE_BIT, 0, 0, nullptr, 0, nullptr, 1, &b);
            } else {
            transition(back, VkImageSubresourceRange{VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1}, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL);
            VkImageMemoryBarrier b{VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER};
            b.oldLayout = VK_IMAGE_LAYOUT_UNDEFINED; b.newLayout = VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL;
            b.dstAccessMask = VK_ACCESS_TRANSFER_WRITE_BIT;
            b.srcQueueFamilyIndex = b.dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
            b.image = s->images[index];
            b.subresourceRange = VkImageSubresourceRange{VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
            barrier(b, VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT);
            flush_barriers();
            if (back->vk_format == s->format && back->width == s->out_width && back->height == s->out_height) {
                VkImageCopy copy{};
                copy.srcSubresource = copy.dstSubresource = VkImageSubresourceLayers{VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1};
                copy.extent = VkExtent3D{s->out_width, s->out_height, 1};
                vk.vkCmdCopyImage(cmd, back->image, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL, s->images[index], VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &copy);
            } else {
                VkImageBlit blit{};
                blit.srcSubresource = blit.dstSubresource = VkImageSubresourceLayers{VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1};
                blit.srcOffsets[1] = VkOffset3D{int32_t(back->width), int32_t(back->height), 1};
                blit.dstOffsets[1] = VkOffset3D{int32_t(s->out_width), int32_t(s->out_height), 1};
                vk.vkCmdBlitImage(cmd, back->image, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL, s->images[index], VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &blit, VK_FILTER_LINEAR);
            }
            b.oldLayout = VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL; b.newLayout = VK_IMAGE_LAYOUT_PRESENT_SRC_KHR;
            b.srcAccessMask = VK_ACCESS_TRANSFER_WRITE_BIT; b.dstAccessMask = 0;
            vk.vkCmdPipelineBarrier(cmd, VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_BOTTOM_OF_PIPE_BIT, 0, 0, nullptr, 0, nullptr, 1, &b);
            }
            back->last_use = gpu.serial();
            VkSemaphore rendered = s->rendered[index];
            VkSwapchainKHR swapchain = s->swapchain;
            gpu.submit(acquire, upscale ? VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT : VK_PIPELINE_STAGE_TRANSFER_BIT, rendered,
                       [s, swapchain, rendered, index, frame = frames + 1] {
                VkPresentInfoKHR pi{VK_STRUCTURE_TYPE_PRESENT_INFO_KHR};
                pi.waitSemaphoreCount = 1; pi.pWaitSemaphores = &rendered;
                pi.swapchainCount = 1; pi.pSwapchains = &swapchain; pi.pImageIndices = &index;
                VkResult result = vk.vkQueuePresentKHR(gpu.queue, &pi);
                if (result == VK_ERROR_OUT_OF_DATE_KHR || result == VK_ERROR_SURFACE_LOST_KHR) s->recreate = true;
                if (result == VK_ERROR_DEVICE_LOST) stop("vkQueuePresentKHR: %s", vk_result(result));
                if (frostpunk_frame_profile_present && (result == VK_SUCCESS || result == VK_SUBOPTIMAL_KHR))
                    frostpunk_frame_profile_present(s, frame, now_ns(), int32_t(result));
            });
            s->acquire_index = (s->acquire_index + 1) % std::size(s->acquire);
            presented = true;
        } else if (host->present_result) host->present_result(int32_t(result));
    }
    if (!presented) {
        flush_barriers();
        gpu.submit();
    }
    ++frames;
    trace_poll();
    guard_present(frames);
    if (frames % 120 == 60) compact_stream();
    if (frames % 600 == 300) {
        static const char* const names[PE_COUNT] = {"other", "targets", "clear_rtv", "clear_dsv", "clear_uav", "split", "dispatch", "unmap",
                                                     "update_buffer", "update_texture", "copy", "copy_region", "mips", "wait", "flush", "forget",
                                                     "policy", "present"};
        char line[512];
        int at = snprintf(line, sizeof(line), "RDVK_PASSES per frame:");
        for (int i = 0; i < PE_COUNT; ++i)
            if (pass_ends[i] && at < int(sizeof(line)) - 32) at += snprintf(line + at, sizeof(line) - size_t(at), " %s=%.1f", names[i], double(pass_ends[i]) / 600.0);
        for (uint64_t& n : pass_ends) n = 0;
        log("%s", line);
        if (query_stats[0] || query_stats[2])
            log("RDVK_QUERIES per 600 frames: begin=%llu end=%llu getdata=%llu ready=%llu not_ready=%llu visible=%llu",
                (unsigned long long)query_stats[0], (unsigned long long)query_stats[1], (unsigned long long)query_stats[2],
                (unsigned long long)query_stats[3], (unsigned long long)query_stats[4], (unsigned long long)query_stats[5]);
        for (uint64_t& n : query_stats) n = 0;
        /* Dynamic buffers by size class: count, bytes, DISCARDs in the last 600 frames, at home. */
        static const uint32_t limits[5] = {4096, 65536, 1u << 20, 16u << 20, UINT32_MAX};
        uint64_t count[5] = {}, bytes[5] = {}, discards[5] = {}, home[5] = {};
        for_each_dynamic_buffer([&](Buffer* b) {
            int k = 0;
            while (b->desc.ByteWidth > limits[k]) ++k;
            ++count[k]; bytes[k] += b->desc.ByteWidth; discards[k] += b->discards; home[k] += b->home != VK_NULL_HANDLE;
            b->discards = 0;
        });
        log("RDVK_DYNAMIC <=4K %llu/%lluKB/%llu/%llu <=64K %llu/%lluKB/%llu/%llu <=1M %llu/%lluKB/%llu/%llu <=16M %llu/%lluKB/%llu/%llu "
            ">16M %llu/%lluKB/%llu/%llu (count/bytes/discards per 600 frames/at home)",
            (unsigned long long)count[0], (unsigned long long)(bytes[0] >> 10), (unsigned long long)discards[0], (unsigned long long)home[0],
            (unsigned long long)count[1], (unsigned long long)(bytes[1] >> 10), (unsigned long long)discards[1], (unsigned long long)home[1],
            (unsigned long long)count[2], (unsigned long long)(bytes[2] >> 10), (unsigned long long)discards[2], (unsigned long long)home[2],
            (unsigned long long)count[3], (unsigned long long)(bytes[3] >> 10), (unsigned long long)discards[3], (unsigned long long)home[3],
            (unsigned long long)count[4], (unsigned long long)(bytes[4] >> 10), (unsigned long long)discards[4], (unsigned long long)home[4]);
        gpu.stream.log_chunks();
        gpu.staging.log_chunks();
    }
    if (frames % 600 == 0) {
        /* Render-thread synchronisation per presented frame (the 600 frames since the last line). */
        Gpu::SyncStats& y = gpu.sync;
        const double ms = 600.0 * 1e6;
        log("RDVK_SYNC marker=%d per_frame: status_calls=%.2f status_ms=%.3f fence_waits=%.2f fence_ms=%.3f slot_waits=%.2f "
            "slot_ms=%.3f submits=%.2f submit_ms=%.3f present_ms=%.3f acquire_ms=%.3f map_staging=%.2f map_waits=%.2f map_ms=%.3f "
            "map_flags=%llu polls=%.2f",
            gpu.has_marker() ? 1 : 0, double(y.status_calls) / 600.0, double(y.status_ns) / ms, double(y.fence_waits) / 600.0,
            double(y.fence_wait_ns) / ms, double(y.slot_waits) / 600.0, double(y.slot_wait_ns) / ms, double(y.submits) / 600.0,
            double(y.submit_ns) / ms, double(y.present_ns) / ms, double(y.acquire_ns) / ms, double(y.map_staging) / 600.0,
            double(y.map_waits) / 600.0, double(y.map_wait_ns) / ms, (unsigned long long)y.map_flags, double(y.poll_calls) / 600.0);
        y = Gpu::SyncStats{};
        Ring::Stats ring = gpu.stream.stats();
        log("RDVK_FRAME frames=%llu draws=%llu passes=%llu pipelines=%llu stream_mb=%llu stream_chunks=%u idle=%u pinned=%u "
            "moved_home=%llu/%lluKB memory_mb=%llu/%llu",
            (unsigned long long)frames, (unsigned long long)draws, (unsigned long long)passes, (unsigned long long)pipelines_created,
            (unsigned long long)(gpu.stream.bytes() >> 20), ring.chunks, ring.idle, ring.pinned, (unsigned long long)home_buffers_,
            (unsigned long long)(home_bytes_ >> 10), (unsigned long long)(gpu.memory.used_bytes() >> 20),
            (unsigned long long)(gpu.memory.allocated_bytes() >> 20));
    }
    cmd_ = gpu.cmd();
    reset_command_state();
}
