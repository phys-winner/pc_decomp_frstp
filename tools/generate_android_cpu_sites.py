"""Pin the approved Windows CPU repairs for a separate Android static helper."""
import hashlib
import json
from pathlib import Path
import re
import capstone
import pefile

ROOT = Path(__file__).resolve().parents[1]


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    config = json.loads((ROOT / 'port.json').read_text())
    original = Path(config['game_directory']) / 'Frostpunk.exe'
    assert digest(original) == config['original_exe_sha256']
    pe = pefile.PE(str(original), fast_load=True)
    decoder = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    files = ['native/windows/simd_integer.c', 'native/windows/simd_float.c', 'native/windows/host.c',
             'research/windows-packed-compare-overlay.json']
    rows = {}
    ops = {'PMULLD': 0, 'PMOVZXBD': 1, 'PABSD': 2, 'PSADBW': 3, 'PMOVSXDQ': 4,
           'PEXTRD': 5, 'CVTTPD2DQ': 6, 'HADDPS': 7}
    integer = (ROOT / files[0]).read_text()
    pattern = r'\{UINT64_C\((0x[0-9a-f]+)\), "([^"]+)", \{([^}]+)\}, (\d+), (\w+), (\d+), (\d+)\}'
    for va, text, data, size, op, dst, src in re.findall(pattern, integer):
        raw = bytes(int(b, 16) for b in data.split(','))
        assert len(raw) == int(size)
        rows[int(va, 16)] = dict(instruction=text, bytes=raw.hex(), operation=ops[op],
                               destination=int(dst), source=int(src), lane=0)
    floating = (ROOT / files[1]).read_text()
    for va, text, data, op, dst, src in re.findall(
            r'\{UINT64_C\((0x[0-9a-f]+)\), "([^"]+)", \{([^}]+)\}, (CVTTPD2DQ|HADDPS), (\d+), (\d+)\}', floating):
        rows[int(va, 16)] = dict(instruction=text, bytes=bytes(int(b, 16) for b in data.split(',')).hex(),
                               operation=ops[op], destination=int(dst), source=int(src), lane=0)
    host = (ROOT / files[2]).read_text()
    gprs = ['rax', 'rcx', 'rdx', 'rbx', 'rsp', 'rbp', 'rsi', 'rdi',
            'r8', 'r9', 'r10', 'r11', 'r12', 'r13', 'r14', 'r15']
    for va, text, escaped, size, dst, src, lane in re.findall(
            r'PEXTRD_SITE\((0x[0-9a-f]+),"([^"]+)","([^"]+)",(\d+),(\w+),(\d+),(\d+)\)', host):
        raw = bytes.fromhex(escaped.replace('\\x', ''))
        assert len(raw) == int(size)
        rows[int(va, 16)] = dict(instruction=text, bytes=raw.hex(), operation=ops['PEXTRD'],
                               destination=gprs.index(dst), source=int(src), lane=int(lane))
    pmov = host.split('static const uint64_t pmovsxdq_sites[]=')[1].split(';')[0]
    for va in re.findall(r'UINT64_C\((0x[0-9a-f]+)\)', pmov):
        rows[int(va, 16)] = dict(instruction='pmovsxdq xmm2, xmm1', bytes='660f3825d1',
                               operation=ops['PMOVSXDQ'], destination=2, source=1, lane=0)
    assert len(rows) == 84
    metadata = json.loads((ROOT / 'generated/frostpunk-x64/recomp_meta.json').read_text())
    for row in rows.values():
        row['canonical_locations'] = []
    watched = {}
    for path in (ROOT / 'generated/frostpunk-x64').glob('recomp_funcs_*.c'):
        for line, text in enumerate(path.read_text().splitlines(), 1):
            match = re.search(r'RECOMP_TODO\(0x([0-9A-F]+), "([^"]+)"\)', text)
            if match and int(match[1], 16) in rows:
                row = rows[int(match[1], 16)]
                assert match[2] == row['instruction']
                assert digest(path) == metadata['generated_files'][path.name]
                name = str(path.relative_to(ROOT)).replace('\\', '/')
                watched[name] = digest(path)
                row['canonical_locations'].append(dict(path=name, line=line))
    sites = []
    for va, row in sorted(rows.items()):
        raw = bytes.fromhex(row['bytes'])
        assert pe.get_data(va - pe.OPTIONAL_HEADER.ImageBase, len(raw)) == raw
        ins = list(decoder.disasm(raw, va))
        assert len(ins) == 1 and ins[0].size == len(raw)
        assert ins[0].mnemonic + ' ' + ins[0].op_str == row['instruction']
        assert row['canonical_locations']
        sites.append(dict(va=hex(va), **row))
    packed = json.loads((ROOT / files[3]).read_text())
    assert packed['success'] and packed['scope'] == 'all' and len(packed['sites']) == 212
    gates = {int(r['va'], 16): r['bytes'] for r in sites}
    for row in packed['sites']:
        va = int(row['va'], 16)
        assert va not in gates
        raw = bytes.fromhex(row['bytes'])
        assert pe.get_data(va - pe.OPTIONAL_HEADER.ImageBase, len(raw)) == raw
        gates[va] = row['bytes']
    include = ['/* Generated by tools/generate_android_cpu_sites.py; original bytes remain data. */',
               'static const fp_aot_site fp_aot_sites[]={']
    for row in sites:
        literal = '"' + ''.join('\\x' + row['bytes'][i:i+2] for i in range(0, len(row['bytes']), 2)) + '"'
        include.append('    {UINT64_C(%s),"%s",%s,%d,%d,%d,%d},' %
                       (row['va'], row['instruction'], literal, row['operation'], row['destination'], row['source'], row['lane']))
    include += ['};', 'static const fp_aot_gate fp_aot_gates[]={']
    for va, raw in sorted(gates.items()):
        literal = '"' + ''.join('\\x' + raw[i:i+2] for i in range(0, len(raw), 2)) + '"'
        include.append('    {UINT64_C(0x%x),%d,%s},' % (va, len(raw)//2, literal))
    include.append('};')
    out = ROOT / 'android/host/aot_cpu_sites.inc'
    out.write_text('\n'.join(include) + '\n', encoding='utf-8', newline='\n')
    manifest = dict(success=True, original_exe_sha256=config['original_exe_sha256'],
                    producer=dict(path='tools/generate_android_cpu_sites.py', sha256=digest(Path(__file__))),
                    reference_inputs={name: digest(ROOT/name) for name in files}, canonical_sources=watched,
                    count=len(sites), occurrences=sum(len(r['canonical_locations']) for r in sites),
                    excluded_xgetbv='0x141ae0d80', packed_gate_count=212, gates=len(gates), sites=sites,
                    outputs={'android/host/aot_cpu_sites.inc': digest(out)})
    (ROOT/'research/android-aot-cpu-sites.json').write_text(json.dumps(manifest, indent=2)+'\n')
    print(json.dumps({k: manifest[k] for k in ['success','count','occurrences','gates']}))


if __name__ == '__main__':
    main()
