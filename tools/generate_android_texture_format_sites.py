"""Generate only the two private ASTC adapter byte gates and fixture baselines."""
import hashlib
import json
from pathlib import Path
import pefile

ROOT=Path(__file__).resolve().parents[1]
SITES=((0x140d95650,0x288,'generated/frostpunk-x64/recomp_funcs_0793.c'),
       (0x140f499a0,0x284,'generated/frostpunk-x64/recomp_funcs_0819.c'))


def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    config=json.loads((ROOT/'port.json').read_text());original=Path(config['game_directory'])/'Frostpunk.exe'
    expected='45d6a087515fab5e5fc55e673699b04f4d207da09958fd274ffe7467d5a09bdc'
    if sha(original)!=expected:raise ValueError('Original executable changed')
    pe=pefile.PE(str(original),fast_load=True);base=pe.OPTIONAL_HEADER.ImageBase
    meta_path=ROOT/'generated/frostpunk-x64/recomp_meta.json';meta=json.loads(meta_path.read_text())
    if meta['original_exe_sha256']!=expected:raise ValueError('Canonical lift original identity differs')
    body=['/* Generated by tools/generate_android_texture_format_sites.py. */'];rows=[];baselines=[]
    for index,(va,size,source_name)in enumerate(SITES):
        code=pe.get_data(va-base,size);source=ROOT/source_name
        if len(code)!=size or sha(source)!=meta['generated_files'][source.name]:raise ValueError('Source preimage changed')
        name=f'L_{va:012X}';text=source.read_text();first=text.index(f'void {name}(CPU *c)\n')
        end=text.find('\nvoid ',first+1)
        if end<0:end=len(text)
        baselines.append(text[first:end])
        body.append(f'static const unsigned char texture_bytes_{index}[] =')
        for pos in range(0,size,32):body.append('    "'+''.join('\\x%02x'%b for b in code[pos:pos+32])+'"')
        body[-1]+=';'
        rows.append(dict(va=hex(va),bytes=size,original_bytes_sha256=hashlib.sha256(code).hexdigest(),
                         canonical=dict(path=source_name,sha256=sha(source),symbol=name)))
    body.append('static const texture_site texture_sites[] = {')
    body.extend(f'    {{UINT64_C({r["va"]}),{r["bytes"]},texture_bytes_{i}}},'for i,r in enumerate(rows))
    body.append('};')
    output=ROOT/'android/host/texture_format_sites.inc';output.write_text('\n'.join(body)+'\n',encoding='utf-8',newline='\n')
    out=ROOT/'build/android-texture-formats';out.mkdir(parents=True,exist_ok=True)
    baseline=out/'canonical_bodies.inc';baseline.write_text('\n'.join(baselines)+'\n',encoding='utf-8',newline='\n')
    manifest=dict(success=True,original_exe_sha256=expected,canonical_metadata_sha256=sha(meta_path),sites=rows,
        producer=dict(path=str(Path(__file__).relative_to(ROOT)),sha256=sha(__file__)),
        outputs={str(p.relative_to(ROOT)):sha(p)for p in(output,baseline)},
        existing_CPU_build_producers_modified=False,canonical_modified=False,device_actions=False)
    path=out/'adapter-manifest.json';path.write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps(dict(success=True,sites=2,bytes=sum(r['bytes']for r in rows),manifest=str(path)),indent=2))


if __name__=='__main__':main()
