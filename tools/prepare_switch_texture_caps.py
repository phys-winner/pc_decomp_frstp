"""Derive world-texture mip limits from the supplied Switch archives; no game data writes."""
import ctypes
import hashlib
import json
from pathlib import Path
import struct
from prepare_raw_archives import entries
from prepare_switch_ui_assets import SWITCH,ZSTD,names
from prepare_ui_astc_archives import source

ROOT=Path(__file__).resolve().parents[1]
OUTPUT=ROOT/'android/host/switch_texture_caps.inc'
# Effects also supply UI frost/temperature masks; leave their shared textures intact.
PREFIXES={'characters','buildings','environment','resources','citydetail','trees'}
NUMERICAL=('heightmap','lookup','_lut','_sdf','gradient','density','lightmap','heatzone','snowmelt','snow_melt','heat_zone')
def sha(p):
    with p.open('rb') as f:return hashlib.file_digest(f,'sha256').hexdigest()
def select(name,width,height,mips,target):
    if name.split('/')[0] not in PREFIXES or any(w in name for w in NUMERICAL):return 0
    for skip in range(1,mips):
        if [max(1,width>>skip),max(1,height>>skip)]==target:return skip
    return 0
def main():
    assert select('ui/test.texture',1024,1024,11,[256,256])==0
    assert select('effects/quadtextures/smears/bigsplotch2forfreezingtobbar.texture',1024,1024,11,[256,256])==0
    assert select('environment/heightmap.texture',1024,1024,11,[256,256])==0
    assert select('buildings/test.texture',1024,512,11,[256,128])==2
    assert select('buildings/test.texture',1024,512,1,[256,128])==0
    assert select('buildings/test.texture',1024,512,11,[256,256])==0
    receipt,paths,_,pc=source()
    index=SWITCH/'textures-s3.idx';data=SWITCH/'textures-s3.dat';strings=SWITCH/'textures-s3.str'
    mapping=names(strings.read_bytes());raw=index.read_bytes();rows=entries(b'\0\2\1'+raw[3:],data.stat().st_size)
    inputs={str(p):sha(p) for p in [index,data,strings,paths['textures-s3.idx']]}
    snapshots={p:(p.stat().st_size,p.stat().st_mtime_ns) for p in [data,paths['textures-s3.dat']]}
    lib=ctypes.CDLL(str(ZSTD));lib.ZSTD_decompress.argtypes=[ctypes.c_void_p,ctypes.c_size_t,ctypes.c_void_p,ctypes.c_size_t];lib.ZSTD_decompress.restype=ctypes.c_size_t
    result=[]
    with data.open('rb') as sf,paths['textures-s3.dat'].open('rb') as pf:
        for key,stored,decoded,offset,flag in rows:
            name=mapping[key]
            if name.split('/')[0] not in PREFIXES or any(w in name for w in NUMERICAL) or key not in pc:continue
            row,record=pc[key]
            if record['new_format']!=0x36545341 or record['faces']!=1 or record['mips']<2:continue
            pf.seek(row[3]);header=pf.read(144);w,h,fmt,mips=struct.unpack_from('<4I',header)
            assert fmt==0x36545341 and mips==record['mips'] and 0<w<=16384 and 0<h<=16384
            assert 28<=decoded<=64*1024*1024
            sf.seek(offset);packed=sf.read(stored);assert len(packed)==stored
            if flag:
                output=ctypes.create_string_buffer(decoded);assert lib.ZSTD_decompress(output,decoded,packed,len(packed))==decoded;payload=output.raw
            else:payload=packed
            assert len(payload)==decoded
            if struct.unpack_from('<I',payload)[0]!=0x1c7865:continue
            target=list(struct.unpack_from('<HH',payload,12));skip=select(name,w,h,mips,target)
            if not skip:continue
            sizes=[]
            for i in range(mips):
                mw,mh,n=struct.unpack_from('<HHI',header,16+8*i)
                assert (mw,mh)==(max(1,w>>(mips-1-i)),max(1,h>>(mips-1-i)))
                assert n==((mw+5)//6)*((mh+5)//6)*16;sizes.append(n)
            assert 144+sum(sizes)==row[1]
            result.append(dict(key=key,name=name,width=w,height=h,mips=mips,skip=skip,target=target,source_bytes=sum(sizes),capped_bytes=sum(sizes[:-skip])))
    result.sort(key=lambda r:r['key']);assert result and len({r['key'] for r in result})==len(result)
    assert all((p.stat().st_size,p.stat().st_mtime_ns)==v for p,v in snapshots.items())
    assert inputs=={p:sha(Path(p)) for p in inputs}
    text='/* Generated by tools/prepare_switch_texture_caps.py; only matching world textures. */\n'
    text+='\n'.join('{0x%08xu,%u,%u,%u},'%(r['key'],r['width'],r['height'],r['skip']) for r in result)+'\n'
    OUTPUT.write_text(text,newline='\n')
    report=dict(inputs=inputs,pc_archive_sha256=receipt['outputs']['textures-s3.dat']['sha256'],producer_sha256=sha(Path(__file__)),output_sha256=sha(OUTPUT),count=len(result),entries=result)
    (ROOT/'research/switch-performance-textures.json').write_text(json.dumps(report,indent=1)+'\n')
    print(json.dumps(dict(count=len(result),output_sha256=sha(OUTPUT),source_mib=sum(r['source_bytes'] for r in result)/2**20,capped_mib=sum(r['capped_bytes'] for r in result)/2**20)),flush=True)
if __name__=='__main__':main()
