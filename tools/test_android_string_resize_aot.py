"""Generate/test one byte-pinned static string-resize scheduling adapter; no device."""
import hashlib
import json
from pathlib import Path
import subprocess
import sys

import capstone
import pefile
from leaf_probe import ROOT, windows_toolchain

OUT = ROOT / 'build/android-string-resize-test'
CANONICAL = ROOT / 'generated/frostpunk-x64/recomp_funcs_0803.c'
VA, END = 0x140E222E0, 0x140E2240A
ORIGINAL_SHA = '45d6a087515fab5e5fc55e673699b04f4d207da09958fd274ffe7467d5a09bdc'
LOOP = '''L_000140E223E0:
    c->rip = 0x140E223E0ull;
    SET64(c->rax, rd64((c->rdi)));                               /* 000140E223E0: mov rax, qword ptr [rdi] */
    wr8((c->rcx + c->rax*1), (uint8_t)(0x3Fu));                  /* 000140E223E3: mov byte ptr [rcx + rax], 0x3f */
    SET64(c->rcx, (c->rcx + 0x1ull));                            /* 000140E223E7: lea rcx, [rcx + 1] */
    SET64(c->rdx, flags_sub(c, c->rdx, 0x1ull, 8));              /* 000140E223EB: sub rdx, 1 */
    if (!c->zf) goto L_000140E223E0;                             /* 000140E223EF: jne 0x140e223e0 */
'''
PREAMBLE = '''/* Generated by tools/test_android_string_resize_aot.py from one sealed canonical body.
 * Only original 140E223E0..3EF byte filling is scheduled differently. */
#include "string_resize_aot.h"
#include <errno.h>

static int verified;
static int overlap(uint64_t a,uint64_t n,uint64_t b,uint64_t m) {
    return a<=b?b-a<n:a-b<m;
}
static void fill_growth(CPU *c) {
    for(;;) {
        /* Preserve the exact first store and CPU state at every page/alias boundary. */
        c->rip=UINT64_C(0x140e223e0);
        SET64(c->rax,rd64(c->rdi));
        uint64_t written=c->rcx+c->rax;
        wr8(written,0x3f);
        SET64(c->rcx,c->rcx+1);
        SET64(c->rdx,flags_sub(c,c->rdx,1,8));
        if(!c->rdx)return;
        uint64_t next=c->rax+c->rcx;
        uint64_t n=4096u-(next&4095u);
        if(n>c->rdx)n=c->rdx;
        /* A completed byte write proves only its own page. Header/CPU aliases
         * retain original per-byte loads, stores and register materialization. */
        if(written==UINT64_MAX||next!=written+1||((next^written)&~UINT64_C(4095))||next>UINT64_MAX-n||
           overlap(next,n,c->rdi,8)||overlap(next,n,(uintptr_t)c,sizeof(*c))||
           overlap(c->rdi,8,(uintptr_t)c,sizeof(*c))||rd64(c->rdi)!=c->rax)continue;
        int saved_errno=errno;
        memset((void*)(uintptr_t)next,0x3f,(size_t)n);
        errno=saved_errno;
        SET64(c->rcx,c->rcx+n);
        SET64(c->rdx,c->rdx-n);
        flags_sub(c,c->rdx+1,1,8);
        if(!c->rdx)return;
    }
}

'''
GATE = '''
static uint16_t u16(const unsigned char*p){uint16_t v;memcpy(&v,p,2);return v;}
static uint32_t u32(const unsigned char*p){uint32_t v;memcpy(&v,p,4);return v;}
static uint64_t u64(const unsigned char*p){uint64_t v;memcpy(&v,p,8);return v;}
static int fits(size_t a,size_t n,size_t size){return a<=size&&n<=size-a;}
int fp_android_string_resize_init(const void *mapped_pe,size_t image_size) {
    verified=0;const unsigned char*b=mapped_pe;
    if(!b||!fits(0,64,image_size)||u16(b)!=0x5a4d)return 0;
    uint32_t pe=u32(b+0x3c);
    if(!fits(pe,24,image_size)||memcmp(b+pe,"PE\\0\\0",4)||u16(b+pe+4)!=0x8664)return 0;
    uint16_t count=u16(b+pe+6),opt_size=u16(b+pe+20);
    size_t opt=(size_t)pe+24,sections=opt+opt_size;
    if(!count||count>96||opt_size<112||!fits(opt,opt_size,image_size)||u16(b+opt)!=0x20b||
       u64(b+opt+24)!=UINT64_C(0x140000000)||!fits(sections,(size_t)count*40,image_size))return 0;
    uint32_t declared=u32(b+opt+56);size_t offset=0xe222e0;int code=0;
    if(!declared||declared>image_size||!fits(offset,sizeof(original_bytes)-1,declared))return 0;
    for(unsigned i=0;i<count;++i){const unsigned char*s=b+sections+(size_t)i*40;
        uint32_t rva=u32(s+12),n=u32(s+8);
        if((u32(s+36)&0x20000000)&&offset>=rva&&offset-rva<=n&&sizeof(original_bytes)-1<=n-(offset-rva)){code=1;break;}}
    if(!code||memcmp(b+offset,original_bytes,sizeof(original_bytes)-1))return 0;
    verified=1;return 1;
}
void (*fp_android_string_resize_lookup(uint64_t va))(CPU *) {
    return verified&&va==UINT64_C(0x140e222e0)?string_resize:NULL;
}
'''


def sha(path):
    with Path(path).open('rb') as stream: return hashlib.file_digest(stream, 'sha256').hexdigest()


def body():
    metadata = json.loads((ROOT / 'generated/frostpunk-x64/recomp_meta.json').read_text())
    if metadata['original_exe_sha256'] != ORIGINAL_SHA or sha(CANONICAL) != metadata['generated_files'][CANONICAL.name]:
        raise ValueError('Sealed canonical source drift')
    text = CANONICAL.read_text()
    first = text.index('void L_000140E222E0(CPU *c)\n')
    source = text[first:text.index('\nvoid ', first + 1)]
    if source.count(LOOP) != 1: raise ValueError('Exact six-instruction loop changed')
    return source


def generate():
    config = json.loads((ROOT / 'port.json').read_text())
    original = Path(config['game_directory']) / 'Frostpunk.exe'
    if sha(original) != ORIGINAL_SHA: raise ValueError('Original executable changed')
    pe = pefile.PE(str(original), fast_load=True)
    raw = pe.get_data(VA - pe.OPTIONAL_HEADER.ImageBase, END - VA)
    if len(raw) != END - VA: raise ValueError('Truncated original function')
    instructions = list(capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64).disasm(raw, VA))
    if instructions[-1].address + instructions[-1].size != END or instructions[-1].mnemonic != 'ret':
        raise ValueError('Original body does not end at its exact RET')
    (OUT / 'original-bytes.bin').write_bytes(raw)
    source = body()
    baseline = OUT / 'canonical_body.inc'
    baseline.write_text(source.replace('void L_000140E222E0(', 'static void baseline_resize('), newline='\n')
    replacement = 'L_000140E223E0:\n    fill_growth(c);\n'
    scheduled = source.replace(LOOP, replacement).replace('void L_000140E222E0(', 'static void string_resize(')
    encoded = 'static const unsigned char original_bytes[]=\n' + '\n'.join(
        '    "' + ''.join('\\x%02x' % b for b in raw[at:at + 32]) + '"' for at in range(0, len(raw), 32)) + ';\n'
    target = ROOT / 'android/host/string_resize_aot.c'
    expected = PREAMBLE + encoded + '\n' + scheduled + '\n' + GATE
    target.write_text(expected, newline='\n')
    return dict(path=str(CANONICAL.relative_to(ROOT)), sha256=sha(CANONICAL), symbol='L_000140E222E0'), raw


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    canonical, raw = generate()
    names = ['tools/test_android_string_resize_aot.py', 'tests/android_string_resize_aot_fixture.c',
             'tests/test_android_string_resize_producer.py',
             'android/host/string_resize_aot.c', 'android/host/string_resize_aot.h',
             'native/runtime64/cpu64.h', canonical['path'], 'generated/frostpunk-x64/recomp_meta.json',
             'build/android-string-resize-test/canonical_body.inc', 'build/android-string-resize-test/original-bytes.bin']
    inputs = {name: sha(ROOT / name) for name in names}
    config = json.loads((ROOT / 'port.json').read_text())
    clang = Path(config['android_sdk']) / 'ndk' / config['android_ndk_version'] / 'toolchains/llvm/prebuilt/windows-x86_64/bin/clang.exe'
    bins, env = windows_toolchain()
    commands = []
    def run(args):
        commands.append(list(map(str, args)))
        p = subprocess.run(commands[-1], cwd=OUT, env=env, capture_output=True, text=True, timeout=120)
        if p.returncode: raise RuntimeError(p.stdout + p.stderr)
        return p
    includes = ['-I' + str(ROOT / 'native/runtime64'), '-I' + str(ROOT / 'android/host'), '-I' + str(OUT)]
    sources = [ROOT / 'android/host/string_resize_aot.c', ROOT / 'tests/android_string_resize_aot_fixture.c']
    objects = []
    for source in sources:
        obj = OUT / (source.stem + '.obj'); objects.append(obj)
        run([clang, '--target=x86_64-pc-windows-msvc', '-O2', '-std=c11', '-fno-strict-aliasing', '-fwrapv',
             '-D_CRT_SECURE_NO_WARNINGS', *includes, '-c', source, '-o', obj])
    host = OUT / 'string-resize-host.exe'
    run([bins / 'link.exe', '/nologo', '/OUT:' + str(host), *objects, 'libcmt.lib', 'oldnames.lib', 'kernel32.lib'])
    completed = run([host])
    result = json.loads(completed.stdout)
    benchmark = json.loads(completed.stderr)
    if not result['success']: raise ValueError('Host differential failed')
    arm = OUT / 'string-resize-arm64'
    run([clang, '--target=aarch64-linux-android30', '-O2', '-std=c11', '-fno-strict-aliasing', '-fwrapv',
         '-ffp-contract=off', '-Wl,-z,max-page-size=16384', *includes, *sources, '-lm', '-o', arm])
    drift = run([sys.executable, '-X', 'utf8', '-B', ROOT / 'tests/test_android_string_resize_producer.py'])
    (OUT / 'producer-tests.log').write_text(drift.stdout + drift.stderr)
    if inputs != {name: sha(ROOT / name) for name in inputs}: raise ValueError('Adapter source drift during build')
    record = dict(success=True, original_exe_sha256=ORIGINAL_SHA, target_va=hex(VA), changed_loop_va='0x140e223e0',
                  original_bytes=raw.hex(), gate_length=len(raw), canonical=canonical, source_hashes=inputs,
                  host=result, benchmark=benchmark, drift_tests=dict(success=True, cases=4, log_sha256=sha(OUT / 'producer-tests.log')),
                  host_binary_sha256=sha(host),
                  arm=dict(compiled=True, executed=False, binary=str(arm.relative_to(ROOT)), binary_sha256=sha(arm)),
                  original_bytes_executed=False, canonical_modified=False, device_actions=False, commands=commands)
    receipt = ROOT / 'research/android-string-resize-validation.json'
    receipt.write_text(json.dumps(record, indent=2) + '\n')
    print(json.dumps(dict(success=True, host=result, arm=record['arm'], receipt=str(receipt)), indent=2))


if __name__ == '__main__': main()
